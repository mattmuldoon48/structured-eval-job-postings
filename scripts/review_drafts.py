import argparse
import json
from pathlib import Path
from typing import Any

from rich.console import Console

from structured_eval.schema import JobPostingLabel


ROOT = Path(__file__).resolve().parents[1]
RAW_PATH = ROOT / "data" / "raw" / "job_postings.jsonl"
LABELED_PATH = ROOT / "data" / "labeled" / "labeled_jobs.jsonl"
DRAFT_MARKER = "needs human review"
console = Console()


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8") as stream:
        return [json.loads(line) for line in stream if line.strip()]


def write_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    path.write_text(
        "".join(json.dumps(record, ensure_ascii=False) + "\n" for record in records),
        encoding="utf-8",
    )


def preview_text(text: str, limit: int = 1200) -> str:
    return text if len(text) <= limit else text[:limit].rstrip() + "..."


def prompt_edit_field(name: str, value: Any) -> Any:
    display = json.dumps(value, ensure_ascii=False)
    raw = input(f"{name} [{display}]: ").strip()
    if raw == "":
        return value
    if raw.lower() == "null":
        return None
    if name in {"required_skills", "nice_to_have_skills"}:
        return [item.strip() for item in raw.split(",") if item.strip()]
    if name in {"salary_min", "salary_max"}:
        return int(raw)
    if name == "required_years_experience":
        return float(raw)
    if name in {"security_clearance_required", "sponsorship_available"}:
        lowered = raw.lower()
        if lowered in {"true", "yes", "y", "1"}:
            return True
        if lowered in {"false", "no", "n", "0"}:
            return False
        return None
    return raw


def draft_indexes(labels: list[dict[str, Any]]) -> list[int]:
    return [
        index
        for index, record in enumerate(labels)
        if DRAFT_MARKER in str(record.get("labeling_notes") or "")
    ]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Review draft labels generated by batch labeling.")
    parser.add_argument("--limit", type=int, default=None, help="Maximum draft labels to review.")
    return parser.parse_args()


def run() -> None:
    args = parse_args()
    raw_by_id = {record["id"]: record for record in load_jsonl(RAW_PATH)}
    labels = load_jsonl(LABELED_PATH)
    indexes = draft_indexes(labels)
    if args.limit is not None:
        indexes = indexes[: args.limit]

    if not indexes:
        console.print("[green]No draft labels found.[/green]")
        return

    reviewed = 0
    for position, label_index in enumerate(indexes, start=1):
        record = labels[label_index]
        job_id = record["id"]
        raw = raw_by_id.get(job_id, {})
        console.rule(f"{job_id} ({position}/{len(indexes)})")
        console.print("[bold]Raw posting preview[/bold]")
        console.print(preview_text(raw.get("text", "")))
        console.print("\n[bold]Current label[/bold]")
        console.print_json(json.dumps(record, ensure_ascii=False))

        action = input("\n[a]ccept, [e]dit, [s]kip, [q]uit: ").strip().lower()
        if action in {"q", "quit"}:
            break
        if action in {"s", "skip", ""}:
            continue
        if action in {"e", "edit"}:
            data = {key: value for key, value in record.items() if key != "id"}
            for field_name in JobPostingLabel.model_fields:
                data[field_name] = prompt_edit_field(field_name, data.get(field_name))
            updated = JobPostingLabel.model_validate(data).model_dump(mode="json")
            labels[label_index] = {"id": job_id, **updated}
        elif action in {"a", "accept"}:
            labels[label_index] = {**record, "labeling_notes": None}
        else:
            console.print("[yellow]Unknown action; skipping.[/yellow]")
            continue

        reviewed += 1
        write_jsonl(LABELED_PATH, labels)
        console.print(f"[green]Saved review for {job_id}[/green]")

    console.print(f"[green]Reviewed {reviewed} draft label(s).[/green]")


if __name__ == "__main__":
    run()
