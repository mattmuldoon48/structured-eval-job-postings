import argparse
import json
from pathlib import Path
from typing import Any

from rich.console import Console

from structured_eval.label_assist import generate_draft_label


ROOT = Path(__file__).resolve().parents[1]
RAW_PATH = ROOT / "data" / "raw" / "job_postings.jsonl"
LABELED_PATH = ROOT / "data" / "labeled" / "labeled_jobs.jsonl"
console = Console()
DRAFT_NOTE = "Draft label generated by extract_v4; needs human review."


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.exists():
        return []
    with path.open("r", encoding="utf-8") as stream:
        return [json.loads(line) for line in stream if line.strip()]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate draft labels for unlabeled raw job postings.")
    parser.add_argument("--limit", type=int, default=None, help="Maximum unlabeled jobs to label.")
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show which jobs would be labeled without calling the model or writing labels.",
    )
    return parser.parse_args()


def unlabeled_records() -> list[dict[str, Any]]:
    raw_records = load_jsonl(RAW_PATH)
    labeled_ids = {record.get("id") for record in load_jsonl(LABELED_PATH)}
    return [record for record in raw_records if record.get("id") not in labeled_ids]


def append_label(job_id: str, label_data: dict[str, Any]) -> None:
    label_data = {**label_data, "labeling_notes": DRAFT_NOTE}
    LABELED_PATH.parent.mkdir(parents=True, exist_ok=True)
    with LABELED_PATH.open("a", encoding="utf-8") as stream:
        stream.write(json.dumps({"id": job_id, **label_data}, ensure_ascii=False) + "\n")


def run() -> None:
    args = parse_args()
    records = unlabeled_records()
    if args.limit is not None:
        records = records[: args.limit]

    if not records:
        console.print("[green]No unlabeled raw jobs found.[/green]")
        return

    if args.dry_run:
        for record in records:
            console.print(record["id"])
        console.print(f"[cyan]Would label {len(records)} job(s).[/cyan]")
        return

    for index, record in enumerate(records, start=1):
        job_id = record["id"]
        console.print(f"[cyan]Labeling {job_id}[/cyan] ({index}/{len(records)})")
        label = generate_draft_label(record["text"])
        append_label(job_id, label.model_dump(mode="json"))

    console.print(f"[green]Saved {len(records)} draft label(s) to {LABELED_PATH}[/green]")


if __name__ == "__main__":
    run()
