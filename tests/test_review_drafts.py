from scripts.review_drafts import draft_indexes, preview_text


def test_draft_indexes_finds_labels_that_need_review():
    labels = [
        {"id": "job-001", "labeling_notes": None},
        {"id": "job-002", "labeling_notes": "Draft label generated by extract_v4; needs human review."},
    ]

    assert draft_indexes(labels) == [1]


